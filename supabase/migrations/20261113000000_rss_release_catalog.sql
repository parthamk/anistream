create table if not exists public.rss_release_catalog (
  id bigint generated by default as identity primary key,
  item_key text not null unique,
  source_name text not null default 'Nyaa RSS',
  title text not null,
  anime_title_guess text,
  episode_number numeric,
  language text not null default 'unknown'
    check (language in ('sub', 'dub', 'unknown')),
  quality text,
  category text,
  published_at timestamptz,
  detail_url text,
  seeders integer,
  leechers integer,
  size_label text,
  anime_id integer,
  match_status text not null default 'unmatched'
    check (match_status in ('unmatched', 'matched', 'ignored')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists rss_release_catalog_published_idx
  on public.rss_release_catalog (published_at desc);

create index if not exists rss_release_catalog_anime_idx
  on public.rss_release_catalog (anime_id, episode_number);

alter table public.rss_release_catalog enable row level security;

drop policy if exists "Admins can read RSS release metadata" on public.rss_release_catalog;
create policy "Admins can read RSS release metadata"
  on public.rss_release_catalog for select to authenticated
  using (
    exists (
      select 1 from public.profiles
      where profiles.id = auth.uid()
        and profiles.is_admin = true
    )
  );

drop policy if exists "Admins can update RSS release metadata" on public.rss_release_catalog;
create policy "Admins can update RSS release metadata"
  on public.rss_release_catalog for update to authenticated
  using (
    exists (
      select 1 from public.profiles
      where profiles.id = auth.uid()
        and profiles.is_admin = true
    )
  )
  with check (
    exists (
      select 1 from public.profiles
      where profiles.id = auth.uid()
        and profiles.is_admin = true
    )
  );

drop policy if exists "Admins can delete RSS release metadata" on public.rss_release_catalog;
create policy "Admins can delete RSS release metadata"
  on public.rss_release_catalog for delete to authenticated
  using (
    exists (
      select 1 from public.profiles
      where profiles.id = auth.uid()
        and profiles.is_admin = true
    )
  );

grant select, update, delete on public.rss_release_catalog to authenticated;
